#!/usr/bin/env node
/**
 * Zen Maru Gothic（@fontsource）から、アプリの文字列に必要なサブセットだけを選んで
 * src/styles/fonts.css と src/assets/fonts/*.woff2 を生成する。
 *
 * @fontsource の CSS は 120 以上の unicode-range スライス × ウェイト分の @font-face を含み、
 * そのまま取り込むとビルド後の CSS が 400KB を超えるため、使う文字を含むスライスだけに絞る。
 * 文字は src/**\/*.{ts,tsx} と index.html から収集し、ひらがな・カタカナ・数字・記号は常に含める。
 */
import { copyFile, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')
const PKG = join(ROOT, 'node_modules', '@fontsource', 'zen-maru-gothic')
const OUT_CSS = join(ROOT, 'src', 'styles', 'fonts.css')
const OUT_DIR = join(ROOT, 'src', 'assets', 'fonts')
const WEIGHTS = [500, 700]

/**
 * 常に含める範囲: 基本ラテン（数字・英字）だけ。
 * かな・漢字は実際に使っている文字から判定する（Google Fonts のスライスはかなと漢字が混在しており、
 * かな全体を範囲指定すると 60 以上のスライスを巻き込んでしまうため）。
 * 文言を追加したら `npm run fonts`（dev/build の前に自動実行）で再生成する。
 */
const ALWAYS = [[0x0000, 0x00ff]]

async function collectFiles(dir, out = []) {
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name)
    if (e.isDirectory()) await collectFiles(p, out)
    else if (/\.(tsx?|html)$/.test(e.name)) out.push(p)
  }
  return out
}

async function usedCodePoints() {
  const files = [...(await collectFiles(join(ROOT, 'src'))), join(ROOT, 'index.html')]
  const set = new Set()
  for (const f of files) {
    // コメントは画面に出ないので除く（文字列リテラルだけを対象にする）
    const text = (await readFile(f, 'utf8')).replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:'"`])\/\/.*$/gm, '$1')
    for (const ch of text) set.add(ch.codePointAt(0))
  }
  return set
}

function parseRanges(text) {
  return text.split(',').map((r) => {
    const [a, b] = r.trim().replace(/^U\+/i, '').split('-')
    const start = parseInt(a, 16)
    return [start, b ? parseInt(b, 16) : start]
  })
}

function intersects(ranges, codePoints) {
  for (const [s, e] of ranges) {
    for (const [as, ae] of ALWAYS) if (s <= ae && e >= as) return true
    for (const cp of codePoints) if (cp >= s && cp <= e) return true
  }
  return false
}

async function main() {
  const codePoints = await usedCodePoints()
  await rm(OUT_DIR, { recursive: true, force: true })
  await mkdir(OUT_DIR, { recursive: true })

  const blocks = []
  let copied = 0
  for (const weight of WEIGHTS) {
    const css = await readFile(join(PKG, `${weight}.css`), 'utf8')
    for (const m of css.matchAll(/@font-face\s*{([^}]*)}/g)) {
      const body = m[1]
      const range = body.match(/unicode-range:\s*([^;]+);/)?.[1]
      const woff2 = body.match(/url\(\.\/files\/([^)]+\.woff2)\)/)?.[1]
      if (!range || !woff2) continue
      if (!intersects(parseRanges(range), codePoints)) continue
      await copyFile(join(PKG, 'files', woff2), join(OUT_DIR, woff2))
      copied++
      blocks.push(
        `@font-face{font-family:'Zen Maru Gothic';font-style:normal;font-display:swap;font-weight:${weight};src:url(../assets/fonts/${woff2}) format('woff2');unicode-range:${range.replace(/\s+/g, '')}}`,
      )
    }
  }
  const header = `/* generated by scripts/build-fonts.mjs — do not edit. Zen Maru Gothic (SIL OFL 1.1) via @fontsource */\n`
  await writeFile(OUT_CSS, header + blocks.join('\n') + '\n')
  console.log(`fonts: ${copied} subset files for ${codePoints.size} distinct characters → ${OUT_CSS}`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
